import { expect, test, type Page } from '@playwright/test'
import { collectErrors, expectAccessible, shot } from '../helpers'
import { DIACRITICS, finishClean, sampleStart } from './clean'

// QA module honeypot (S-HP-1): clean install -> decoy -> turn traps on -> test hit -> details; IP and hostname validation.
const SMB = 'SMB (file sharing)'
const call = (page: Page, path: string) => page.evaluate(async (p) => (await fetch(`/api/v1${p}`)).json(), path)
const vis = (page: Page, text: string | RegExp) => page.getByText(text).locator('visible=true').first()

test('clean install: empty page with three steps, switches locked until there is a secondary IP, test hits are labelled', async ({ page, isMobile }) => {
  test.setTimeout(120_000)
  const errors = collectErrors(page)
  await finishClean(page)
  await page.goto('/honeypot')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/No traps are on/)
  await expect(page.getByText('Get started with internal traps in three steps')).toBeVisible()
  await expect(page.getByText('FILESRV-OLD', { exact: true })).toHaveCount(0)
  await expect(page.getByText('192.168.10.240')).toHaveCount(0)
  await expect(vis(page, /No trap is on yet, so there is nothing to record/)).toBeVisible()
  await expect(page.getByRole('switch', { name: `Turn on ${SMB} trap` })).toBeDisabled()
  await expect(page.getByRole('button', { name: `Test trap ${SMB}` })).toBeDisabled()
  await shot(page, 'honeypot', `clean-${isMobile ? 'mobile' : 'desktop'}`)
  await expectAccessible(page, 'honeypot clean')

  const ip = page.getByLabel('Trap secondary IP')
  const host = page.getByLabel('Fake hostname')
  const save = page.getByRole('button', { name: 'Save', exact: true })
  await ip.fill('abc'); await host.fill('FILESRV-OLD'); await save.click()
  await expect(page.getByText(/is not valid/)).toBeVisible()
  await ip.fill('192.168.10.010'); await save.click()
  await expect(page.getByText(/no leading zeros/)).toBeVisible()
  await ip.fill('10.0.0.5'); await save.click()
  await expect(page.getByText(/must be inside the network of the box|must be inside the box's network/)).toBeVisible()
  await ip.fill('192.168.10.250'); await save.click()
  await expect(page.getByText(/the Vedette box's own IP|own IP/)).toBeVisible()
  await ip.fill('192.168.10.255'); await save.click()
  await expect(page.getByText(/not the network or broadcast address/)).toBeVisible()
  await ip.fill('192.168.10.240'); await host.fill('file.srv_old'); await save.click()
  await expect(page.locator('#hp-host-error')).toContainText('letters, digits and hyphens')
  await expect(page.locator('#hp-ip-error')).toHaveCount(0)
  await expect(host).toBeFocused()
  await host.fill(''); await save.click()
  await expect(page.locator('#hp-host-error')).toContainText('Enter a fake hostname')
  await host.fill('FILESRV-OLD'); await host.press('Enter')
  await expect(page.getByText('Decoy saved')).toBeVisible()
  await expect(page.getByText('Get started with internal traps in three steps')).toHaveCount(0)
  await page.reload()
  await expect(ip).toHaveValue('192.168.10.240')

  for (const name of [SMB, 'RDP (remote desktop)', 'SSH', 'MSSQL (SQL Server)', 'HTTP (fake admin page)']) {
    await page.getByRole('switch', { name: `Turn on ${name} trap` }).click()
    await expect(page.getByRole('switch', { name: `Turn on ${name} trap` })).toBeChecked()
  }
  await expect(page.getByText('Listening').locator('visible=true')).toHaveCount(5)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/No trap was hit in the last 7 days/)
  await expect(vis(page, 'No hits yet')).toBeVisible()
  await page.getByRole('button', { name: `Test trap ${SMB}` }).click()
  await expect(page.getByText('Recorded a test hit on the SMB (file sharing) trap').first()).toBeVisible()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/No trap was hit in the last 7 days/)
  const row = page.locator('tr:visible, li:visible').filter({ hasText: 'Vedette box (test)' }).first()
  await expect(row.getByText('Test', { exact: true })).toBeVisible()
  await row.getByRole('link').first().click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/Test hit on the SMB/)
  await expect(page.getByText(/Not an attacker/)).toBeVisible()
  await expect(page.getByText('What to do')).toHaveCount(0)
  await shot(page, 'honeypot', `hit-test-${isMobile ? 'mobile' : 'desktop'}`)
  await page.goto('/honeypot')
  await page.getByRole('switch', { name: `Turn on ${SMB} trap` }).click()
  await expect(page.getByRole('button', { name: `Test trap ${SMB}` })).toBeDisabled()
  expect(errors).toEqual([])
})

test('sample: IP clash, hostname clash, hit timeline, device page panel, missing hit', async ({ page, isMobile }) => {
  test.setTimeout(90_000)
  const errors = collectErrors(page)
  await sampleStart(page)
  await page.goto('/honeypot')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/Traps were hit 2 times in 7 days/)
  const devs = (await call(page, '/inventory/devices')).items as { ip: string; hostname: string | null }[]
  const named = devs.find((d) => d.hostname && d.ip.startsWith('192.168.10.'))!
  const ip = page.getByLabel('Trap secondary IP')
  const host = page.getByLabel('Fake hostname')
  const save = page.getByRole('button', { name: 'Save', exact: true })
  await ip.fill(named.ip); await save.click()
  await expect(page.locator('#hp-ip-error')).toContainText('belongs to device')
  await ip.fill('192.168.10.241'); await host.fill(named.hostname!); await save.click()
  await expect(page.locator('#hp-host-error')).toContainText('belongs to device')
  await host.fill('FILESRV-OLD'); await save.click()
  await expect(page.getByText('Decoy saved')).toBeVisible()
  await shot(page, 'honeypot', `sample-${isMobile ? 'mobile' : 'desktop'}`)

  await page.getByRole('link', { name: /\d\d:\d\d/ }).first().click()
  await expect(page.getByRole('table', { name: 'Events around the trap hit' })).toBeVisible()
  await expect(page.getByText('What to do')).toBeVisible()
  await shot(page, 'honeypot', `hit-${isMobile ? 'mobile' : 'desktop'}`)
  await expectAccessible(page, 'hit detail')
  await page.locator('a[href^="/devices/"]').first().click()
  await expect(page.getByRole('heading', { name: 'Internal trap hits' })).toBeVisible()
  await expect(page.getByRole('link', { name: /SMB \(file sharing\) at/ })).toBeVisible()
  await expectAccessible(page, 'device page with trap panel')
  await page.goto('/honeypot/hits/no-such-hit')
  await expect(page.getByRole('alert')).toContainText('No such trap hit')
  expect(errors).toEqual([])
})

test('English only and dark mode: no Vietnamese, error under the right field', async ({ page }) => {
  const errors = collectErrors(page)
  await sampleStart(page)
  await page.emulateMedia({ colorScheme: 'dark' })
  for (const path of ['/honeypot', '/honeypot/hits/hit-seed-1', '/honeypot/hits/hit-seed-2']) {
    await page.goto(path)
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    if (path === '/honeypot') {
      await page.getByLabel('Trap secondary IP').fill('192.168.10.250')
      await page.getByRole('button', { name: 'Save', exact: true }).click()
      await expect(page.getByText(/Vedette box's own IP/)).toBeVisible()
    }
    const text = (await page.locator('main').innerText()).replace(/Sample data/g, '')
    expect(text.match(DIACRITICS), `${path} contains Vietnamese: ${text.match(/.{20}[ăâđêôơư].{20}/i)?.[0]}`).toBeNull()
    await shot(page, 'honeypot', `dark-${path.replace(/\W/g, '_')}`)
    await expectAccessible(page, `${path} dark`)
  }
  expect(errors).toEqual([])
})
