package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
)

var httpMethods = []string{"get", "put", "post", "delete", "patch", "head", "options", "trace"}

// Roles accepted in x-min-role (INV-5: an endpoint without a valid role is refused).
var validRoles = map[string]string{"public": "Public", "viewer": "Viewer", "operator": "Operator", "admin": "Admin"}

// Operation is one row of the generated table.
type Operation struct {
	ID     string
	Method string // upper case
	Path   string // as in the contract, without the /api/v1 server prefix
	Role   string // public | viewer | operator | admin
	Tag    string // module id (first tag)
}

// Operations extracts every operation, sorted by operationId. It fails on a missing operationId,
// a missing or unknown x-min-role, a missing tag or a duplicate operationId.
func Operations(doc map[string]any) ([]Operation, error) {
	paths, _ := doc["paths"].(map[string]any)
	seen := map[string]bool{}
	var ops []Operation
	for _, p := range sortedKeys(paths) {
		item, _ := paths[p].(map[string]any)
		for _, m := range httpMethods {
			op, ok := item[m].(map[string]any)
			if !ok {
				continue
			}
			where := fmt.Sprintf("%s %s", upper(m), p)
			id, _ := op["operationId"].(string)
			if id == "" {
				return nil, fmt.Errorf("apigen: %s: no operationId", where)
			}
			if seen[id] {
				return nil, fmt.Errorf("apigen: %s: duplicate operationId %q", where, id)
			}
			seen[id] = true
			role, _ := op["x-min-role"].(string)
			if _, ok := validRoles[role]; !ok {
				return nil, fmt.Errorf("apigen: %s (%s): x-min-role %q is missing or not one of viewer/operator/admin/public", where, id, role)
			}
			tags, _ := op["tags"].([]any)
			tag := ""
			if len(tags) > 0 {
				tag, _ = tags[0].(string)
			}
			if tag == "" {
				return nil, fmt.Errorf("apigen: %s (%s): no tag", where, id)
			}
			ops = append(ops, Operation{ID: id, Method: upper(m), Path: p, Role: role, Tag: tag})
		}
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i].ID < ops[j].ID })
	return ops, nil
}

func upper(m string) string {
	b := []byte(m)
	for i, c := range b {
		if c >= 'a' && c <= 'z' {
			b[i] = c - 32
		}
	}
	return string(b)
}

// RoutesSource renders the Go file for package routes.
func RoutesSource(ops []Operation) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by core/api/apigen from api/openapi.json (x-min-role, tags); DO NOT EDIT.

// Package routes maps every operationId of the contract to its method, path, minimum role and module.
// The HTTP layer builds its role middleware from this table (INV-5, API_CONVENTIONS 7.4).
package routes

// Role is the minimum role an operation needs. Public needs no session.
type Role string

const (
	Public   Role = "public"
	Viewer   Role = "viewer"
	Operator Role = "operator"
	Admin    Role = "admin"
)

// Operation describes one contract operation. Path has no /api/v1 prefix.
type Operation struct {
	Method  string
	Path    string
	MinRole Role
	Tag     string
}

// Operations is keyed by operationId (the OperationID of ogen's Route and middleware.Request).
var Operations = map[string]Operation{
`)
	for _, o := range ops {
		fmt.Fprintf(&b, "\t%q: {Method: %q, Path: %q, MinRole: %s, Tag: %q},\n", o.ID, o.Method, o.Path, validRoles[o.Role], o.Tag)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("apigen: format routes: %w", err)
	}
	return out, nil
}
