// Every operation of the route table is claimed by exactly one module in contractRoutes, and
// ModuleOf agrees. A new operation or a changed override fails here until the contract is read again.
func TestModuleOfMatchesTheContracts(t *testing.T) {
	t.Parallel()
	claimed := map[string]string{}
	for mod, list := range contractRoutes {
		for _, key := range list {
			if prev, dup := claimed[key]; dup {
				t.Errorf("%s is claimed by both %s and %s", key, prev, mod)
			}
			claimed[key] = mod
		}
	}
	for id, op := range routes.Operations {
		key := op.Method + " " + op.Path
		want, ok := claimed[key]
		if !ok {
			t.Errorf("%s (%s) is in no module's contract list: add it to contractRoutes after reading the contracts", id, key)
			continue
		}
		if got := server.ModuleOf(op); got != want {
			t.Errorf("%s: ModuleOf = %q, the contract says %q", key, got, want)
		}
		delete(claimed, key)
	}
	for key, mod := range claimed {
		t.Errorf("contractRoutes lists %s for %s but the route table has no such operation", key, mod)
	}
}
