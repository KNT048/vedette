package orgtime

// CanonicalZone is the current IANA name of a zone: an old alias from the tz database's "backward" file (Asia/Saigon,
// Asia/Calcutta, Europe/Kiev, US/Eastern) becomes the zone it links to (Asia/Ho_Chi_Minh, Asia/Kolkata, Europe/Kyiv,
// America/New_York); any other name is returned as it is. Browsers still report several of these aliases as the reader's own zone,
// Go's database knows them, but the box's operating system may not: Debian 13 and Ubuntu 26.04 moved them to the optional
// tzdata-legacy package. One zone therefore has one name on every page, in every mail and on the operating system.
func CanonicalZone(name string) string {
	if c, ok := backwardZones[name]; ok {
		return c
	}
	return name
}

