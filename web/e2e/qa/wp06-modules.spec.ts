import { expect, test, type Page } from '@playwright/test'
import { collectErrors, expectAccessible } from '../helpers'
import { begin, noHScroll, stepper, THEMES } from './wp06-shared'

// WP-06 independent check, area 6: "As the admin I switch modules on and off; findings is its own module; turning off mitigation must not hide findings."
// Settings -> Modules; Findings page; a finding's "What to do".
const row = (page: Page, name: RegExp) => page.getByRole('table', { name: 'Modules' }).locator('tbody tr').filter({ hasText: name }).first()

for (const theme of THEMES) {
  test(`modules [${theme}]: findings is its own module; dependency prompt; mitigation off keeps findings`, async ({ page }, info) => {
    const errors = collectErrors(page)
    const shot = stepper(page, info, 'modules', theme)
    await begin(page, theme)
    await page.goto('/settings/modules')
    await expect(page.getByRole('table', { name: 'Modules' })).toBeVisible()
    await shot('list')
    const names = await page.getByRole('table', { name: 'Modules' }).locator('tbody tr td:first-child').allInnerTexts()
    console.log('MODULES', JSON.stringify(names.map((n) => n.replace(/\n+/g, ' / '))))
    const fnd = row(page, /^Findings|Vulnerability findings|^Findings/i)
    // findings: its own row with its own switch and its needs
    const rows = await page.getByRole('table', { name: 'Modules' }).locator('tbody tr').allInnerTexts()
    const fRow = rows.find((r) => /findings/i.test(r.split('\n')[0] ?? ''))
    console.log('FINDINGS ROW', JSON.stringify(fRow))
    expect(fRow, 'a Findings module row').toBeTruthy()
    const fSwitch = page.getByRole('switch', { name: /Turn (on|off) module .*Finding/i })
    await expect(fSwitch).toHaveCount(1)
    await expect(fSwitch).toBeChecked()
    expect(fRow).toMatch(/Inventory/)
    expect(fRow).toMatch(/feed/i)
    // D-57: mitigation is only the "What to do" package and depends on findings
    const mRow = rows.find((r) => /^Mitigation/.test(r))
    console.log('MITIGATION ROW', JSON.stringify(mRow))
    expect.soft(mRow, 'D-57: the Mitigation row says it needs Findings').toMatch(/Findings/)
    // turn feeds off: the prompt lists what depends on it (findings among them)
    const feedsSwitch = page.getByRole('switch', { name: /Turn (on|off) module .*Feeds/i })
    await feedsSwitch.click()
    const dlg = page.getByRole('dialog')
    await expect(dlg).toBeVisible()
    await shot('turn-off-feeds')
    const offText = await dlg.innerText()
    console.log('TURN OFF FEEDS', offText)
    expect(offText).toMatch(/Finding/i)
    await dlg.getByRole('button', { name: 'Turn off' }).click()
    await expect(dlg).toBeHidden()
    // turn findings off, then findings on again while feeds is off -> must ask to turn feeds on too
    await fSwitch.click()
    await page.getByRole('dialog').getByRole('button', { name: 'Turn off' }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    await shot('findings-and-feeds-off')
    await fSwitch.click()
    const deps = page.getByRole('dialog')
    await expect(deps).toBeVisible()
    await shot('deps-prompt')
    console.log('DEPS PROMPT', await deps.innerText())
    await expect(deps.getByRole('heading', { name: 'Turn on the required modules too?' })).toBeVisible()
    await expect(deps.getByRole('listitem').filter({ hasText: /feed/i })).toBeVisible()
    // way back: Cancel leaves findings off and feeds off
    await deps.getByRole('button', { name: 'Cancel' }).click()
    await expect(deps).toBeHidden()
    await expect(fSwitch).not.toBeChecked()
    await expect(feedsSwitch).not.toBeChecked()
    // confirm: both come on
    await fSwitch.click()
    await page.getByRole('dialog').getByRole('button', { name: 'Turn on together' }).click()
    await expect(fSwitch).toBeChecked()
    await expect(feedsSwitch).toBeChecked()
    await shot('both-on')
    // mitigation off: findings still shown, only "What to do" is missing
    const mitSwitch = page.getByRole('switch', { name: /Turn (on|off) module .*(Mitigation|Recommend)/i })
    console.log('MITIGATION SWITCH COUNT', await mitSwitch.count())
    await mitSwitch.click()
    const md = page.getByRole('dialog')
    console.log('TURN OFF MITIGATION', await md.innerText())
    await shot('turn-off-mitigation')
    await md.getByRole('button', { name: 'Turn off' }).click()
    await expect(md).toBeHidden()
    await page.goto('/findings')
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    await shot('findings-mitigation-off')
    const list = await page.locator('main').innerText()
    console.log('FINDINGS PAGE (mitigation off)', list.slice(0, 1200))
    expect(list, 'findings list still shows CVEs').toMatch(/CVE-\d{4}-\d+/)
    expect(list, 'findings page says the whole module is off').not.toMatch(/module is off.*findings|Findings (is|are) off/i)
    const first = page.getByRole('link', { name: /CVE-\d{4}-\d+/ }).first()
    await first.click()
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    await page.waitForTimeout(500)
    await shot('finding-detail-mitigation-off')
    const detail = await page.locator('main').innerText()
    console.log('FINDING DETAIL (mitigation off)', detail.slice(0, 2500))
    expect(detail).toMatch(/CVE-\d{4}-\d+/)
    expect(detail, 'the missing part says why (module off) and how to get it back').toMatch(/mitigation|What to do/i)
    await noHScroll(page, 'finding detail')
    await expectAccessible(page, 'finding detail, mitigation off')
    expect(errors.filter((e) => !/status of (4|5)\d\d/.test(e))).toEqual([])
  })
}
