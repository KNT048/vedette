/** Đổi phiên sang tài khoản khác: ép core_session trước mỗi lần tải trang (một lần ghi muộn của trang cũ không đè được). */
async function asUser(page: Page, userId: string) {
  await page.addInitScript((u) => {
    try {
      const k = 'vedette-mock-db-v3'
      const raw = localStorage.getItem(k)
      if (raw) { const db = JSON.parse(raw); db.core_session = { userId: u }; localStorage.setItem(k, JSON.stringify(db)) }
    } catch { /* bỏ qua */ }
  }, userId)
  await page.reload()
}
const noHorizontalScroll = async (page: Page) => expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
const device = (page: Page) => (page.viewportSize()?.width ?? 1366) < 700 ? 'mobile' : 'desktop'
const noVietnamese = async (page: Page) => expect(await page.locator('body').innerText()).not.toMatch(DIACRITICS)

async function fillOrg(page: Page, o: { tax?: string; size?: string } = {}) {
  await page.getByLabel('Tax code').fill(o.tax ?? '0312345678')
  await page.getByLabel('Head office address').fill('12 Nguyen Hue, District 1, Ho Chi Minh City')
  await page.getByLabel('Line of business').selectOption({ label: 'Retail and trade' })
  await page.getByLabel('Number of staff').fill('45')
  await page.getByLabel('Organisation size').selectOption({ label: o.size ?? 'Small enterprise' })
  await page.getByLabel('Data protection contact').fill('Tran Van An')
  await page.getByLabel('Contact email').fill('anna@acme.example')
  await page.getByLabel('Contact phone').fill('0901234567')
}

test.describe('reports: clean install', () => {
  test('only the box so far: the weekly report counts the box and its finding; empty schedule that is off; empty history; no sample data', async ({ page }) => {
    const errors = collectErrors(page)
    await finishClean(page)
    await page.goto('/reports')
    // The box is the first device even on a clean install (S-INV-5, D-53), so the report is never "no data":
    // it counts the box and its one suspected finding, and nothing from the sample data.
    await expect(page.getByRole('heading', { level: 1 })).toContainText('This week 1 findings are unresolved and 0 devices await approval.')
    await expect(page.getByText('No data for the weekly report yet')).toHaveCount(0)
    await expect(page.getByText('1 (0 awaiting approval)')).toBeVisible()
    await expect(page.getByRole('cell', { name: 'CVE-2026-46300' }).first()).toBeVisible()
    // nothing can be sent while there is no recipient
    await page.getByRole('button', { name: 'Send now' }).click()
    const send = page.getByRole('dialog', { name: 'Send the weekly report now?' })
    await expect(send.getByText('No recipients yet. Add emails under Schedule and recipients.')).toBeVisible()
    await expect(send.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
    await send.getByRole('button', { name: 'Cancel' }).click()
    await expect(page.getByText('No recipients yet.')).toBeVisible()
    await expect(page.getByText('Automatic sending is off.')).toBeVisible()
    await expect(page.getByRole('switch', { name: 'Send automatically every week' })).not.toBeChecked()
    await expect(page.getByText('No report sent yet')).toBeVisible()
    await expect(page.getByText('director@acme.example')).toHaveCount(0)
    await shot(page, 'reports', `weekly-clean-${device(page)}`)
    await expectAccessible(page, 'reports, clean')
    await noHorizontalScroll(page)
    await noVietnamese(page)
    await page.goto('/reports?tab=pdpl')
    const gen = page.getByRole('button', { name: 'Generate report' })
    await expect(gen).toBeDisabled()
    await expect(gen).toHaveAttribute('title', /Save the organisation details first/)
    await expect(page.getByLabel('Organisation name')).toHaveValue('Test Company')
    await shot(page, 'reports', `pdpl-clean-${device(page)}`)
    expect(errors).toEqual([])
  })

  test('schedule: a bad or duplicate email, an email not yet added, turning it on with no recipient; saved values persist; one recipient can be removed', async ({ page }) => {
    await finishClean(page)
    await page.goto('/reports')
    await page.getByRole('switch', { name: 'Send automatically every week' }).click()
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(page.getByText(/needs at least one recipient/)).toBeVisible()
    const mail = page.getByLabel('Recipients', { exact: true })
    await mail.fill('not-an-email')
    await page.getByRole('button', { name: 'Add', exact: true }).click()
    await expect(page.getByText('The email is not valid. Use the form name@company.com.')).toBeVisible()
    await mail.fill('boss@testco.example')
    await mail.press('Enter')
    await mail.fill('boss@testco.example')
    await mail.press('Enter')
    await expect(page.getByText('This email is already in the list.')).toBeVisible()
    await mail.fill('accounts@testco.example') // chưa bấm Add mà bấm Save: không im lặng mất email
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(page.getByText(/Press Add to put this email on the list/)).toBeVisible()
    await mail.press('Enter')
    await page.getByLabel('Day').selectOption('fri')
    await page.getByLabel('Hour').selectOption('17')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(page.getByText('Schedule saved').first()).toBeVisible()
    await expect(page.getByText(/Next send:/)).toBeVisible()
    await page.reload()
    await expect(page.getByText('accounts@testco.example')).toBeVisible()
    await expect(page.getByLabel('Day')).toHaveValue('fri')
    await page.getByRole('button', { name: 'Remove accounts@testco.example' }).click()
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(page.getByText('accounts@testco.example')).toHaveCount(0)
  })
})

test.describe('reports: weekly report (sample data)', () => {
  test('the preview invents no honeypot or log numbers; AI commentary is labelled with the profile; Send now confirms, records history, reopens for printing', async ({ page }) => {
    const errors = collectErrors(page)
    await sampleStart(page)
    await page.goto('/reports')
    await expect(page.getByRole('heading', { level: 1 })).toContainText('findings are unresolved')
    const doc = page.getByRole('article', { name: 'Weekly security report' })
    await expect(doc).toBeVisible()
    await expect(doc).not.toContainText(/Honeypot touches\s*\d/)
    await expect(doc).toContainText('are not part of this report yet')
    await shot(page, 'reports', `weekly-${device(page)}`)
    await expectAccessible(page, 'weekly report')
    await noHorizontalScroll(page)
    await page.getByRole('button', { name: 'Write AI commentary' }).click()
    await expect(doc.getByText('AI-generated, needs human review')).toBeVisible()
    await expect(doc.getByText(/Model claude-haiku-5-5 \(Claude Haiku\)/)).toBeVisible()
    await page.getByRole('button', { name: 'Send now' }).click()
    await expect(page.getByRole('dialog')).toContainText('director@acme.example')
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    const history = page.getByRole('region', { name: 'Sent' })
    const before = await history.getByRole('link', { name: 'View and print' }).count()
    await page.getByRole('button', { name: 'Send now' }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Send', exact: true }).click()
    await expect(page.getByText('Weekly report sent').first()).toBeVisible()
    await expect(history.getByRole('link', { name: 'View and print' })).toHaveCount(before + 1)
    await expect(history.getByText('Manual').first()).toBeVisible()
    await expect(page.getByText(/The email channel has no valid SMTP settings/).first()).toBeVisible()
    await history.getByRole('link', { name: 'View and print' }).first().click()
    await expect(page).toHaveURL(/\/reports\/print\/weekly\/h-/)
    await expect(page.getByRole('article', { name: 'Weekly security report' })).toBeVisible()
    await noVietnamese(page)
    expect(errors).toEqual([])
  })

  test('print page: only the document prints, no sidebar; opens by direct link; Back returns to the right place; an unknown id is explained', async ({ page }) => {
    const errors = collectErrors(page)
    await sampleStart(page)
    await page.goto('/reports/print/weekly')
    await expect(page.getByRole('article', { name: 'Weekly security report' })).toBeVisible()
    await shot(page, 'reports', `print-weekly-screen-${device(page)}`)
    await page.emulateMedia({ media: 'print' })
    await expect(page.getByRole('button', { name: 'Print / Save PDF' })).toBeHidden()
    await expect(page.getByRole('link', { name: 'Back to reports' })).toBeHidden()
    await page.screenshot({ path: `qa-shots/reports/print-weekly-print-${device(page)}.png`, fullPage: true })
    await page.emulateMedia({ media: 'screen' })
    await page.getByRole('link', { name: 'Back to reports' }).click()
    await expect(page).toHaveURL(/\/reports$/)
    await page.goBack()
    await expect(page).toHaveURL(/print\/weekly/)
    await page.goto('/reports/print/weekly/h-missing')
    await expect(page.getByText('This report is not in the history.')).toBeVisible()
    await noVietnamese(page)
    expect(errors.filter((e) => !/404/.test(e))).toEqual([])
  })

  test('viewer (director): can read and print, cannot send or change the schedule, is told which role is needed', async ({ page }) => {
    await sampleStart(page)
    const send = page.getByRole('button', { name: 'Send now' })
    await expect(async () => {
      await asUser(page, 'u-view')
      await page.goto('/reports')
      await expect(send).toHaveAttribute('title', /Operator/, { timeout: 4000 })
    }).toPass({ timeout: 60_000 })
    await expect(page.getByRole('article', { name: 'Weekly security report' })).toBeVisible()
    await expect(send).toBeDisabled()
    await expect(page.getByRole('link', { name: 'Print / Save PDF' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeDisabled()
  })
})

test.describe('reports: data protection assessment under Law 91/2025/QH15 (S-REP-2)', () => {
  test('form: empty, bad tax code, bad email and phone, then valid; typed data is kept; generate, check the legal content, print', async ({ page }) => {
    const errors = collectErrors(page)
    await sampleStart(page)
    await page.goto('/reports?tab=pdpl')
    await expect(page.getByRole('note').first()).toContainText('Assessment support, not legal advice')
    await page.getByLabel('Organisation name').fill('')
    await page.getByRole('button', { name: 'Save details' }).click()
    for (const m of ['Enter the organisation name', 'The tax code is 10 digits', 'Enter the head office address', 'Pick the field of activity', 'Enter the headcount', 'Pick the organisation size', 'Enter the name of the person', 'The email is not valid', 'The phone number starts with 0']) await expect(page.getByText(new RegExp(m)).first()).toBeVisible()
    await page.getByLabel('Organisation name').fill('Sample Company')
    await fillOrg(page, { tax: '123' })
    await page.getByLabel('Contact email').fill('anna@@acme')
    await page.getByLabel('Contact phone').fill('12345')
    await page.getByRole('button', { name: 'Save details' }).click()
    await expect(page.getByText(/The tax code is 10 digits/)).toBeVisible()
    await expect(page.getByText('The email is not valid. Use the form name@company.com.')).toBeVisible()
    await expect(page.getByLabel('Head office address')).toHaveValue(/Nguyen Hue/)
    await page.getByLabel('Tax code').fill('0312345678-001')
    await page.getByLabel('Contact email').fill('anna@acme.example')
    await page.getByLabel('Contact phone').fill('0901 234 567')
    await page.getByLabel('Contact phone').press('Enter') // Enter gửi form
    await expect(page.getByText('Organisation details saved').first()).toBeVisible()
    await page.reload()
    await expect(page.getByLabel('Tax code')).toHaveValue('0312345678-001')
    await page.getByRole('button', { name: 'Generate report' }).click()
    const doc = page.getByRole('article', { name: /Information security and personal data assessment report/ })
    await expect(doc).toBeVisible()
    for (const must of ['91/2025/QH15', 'Decree 356/2025/ND-CP', '72 hours', '60 days', 'Article 23', 'Articles 21, 22', 'Official Gazette No. 18']) await expect(doc).toContainText(must)
    await expect(doc.getByText('Assessment support, not legal advice')).toHaveCount(2)
    await shot(page, 'reports', `pdpl-${device(page)}`)
    await expectAccessible(page, 'assessment')
    await noHorizontalScroll(page)
    await noVietnamese(page)
    await page.getByRole('link', { name: 'Print / Save PDF' }).click()
    await expect(page).toHaveURL(/print\/pdpl/)
    await expect(page.getByRole('article', { name: /Information security and personal data assessment report/ })).toBeVisible()
    await shot(page, 'reports', `print-pdpl-screen-${device(page)}`)
    await page.emulateMedia({ media: 'print' })
    await page.screenshot({ path: `qa-shots/reports/print-pdpl-print-${device(page)}.png`, fullPage: true })
    await page.emulateMedia({ media: 'screen' })
    expect(errors).toEqual([])
  })

  test('size decides the obligations: a micro enterprise is exempt from the dossier and the data protection person; sensitive data makes them mandatory; transfer abroad always applies', async ({ page }) => {
    await sampleStart(page)
    await page.goto('/reports?tab=pdpl')
    await fillOrg(page, { size: 'Micro enterprise' })
    await page.getByRole('checkbox', { name: 'We transfer data abroad' }).check()
    await page.getByRole('button', { name: 'Save details' }).click()
    await expect(page.getByText('Organisation details saved').first()).toBeVisible()
    await page.getByRole('button', { name: 'Generate report' }).click()
    const doc = page.getByRole('article', { name: /Information security and personal data assessment report/ })
    await expect(doc.getByText('Not mandatory at your size')).toHaveCount(2)
    await expect(doc.getByText('Transfer of data abroad').first()).toBeVisible()
    await page.getByRole('checkbox', { name: 'We process sensitive personal data' }).check()
    await page.getByRole('button', { name: 'Save details' }).click()
    await expect(page.getByText('Organisation details saved').first()).toBeVisible()
    await page.getByRole('button', { name: 'Regenerate from new data' }).click()
    await expect(doc.getByText('Not mandatory at your size')).toHaveCount(0)
    await expect(doc.getByText('Sensitive personal data').first()).toBeVisible()
  })

  test('AI commentary: labelled, with the profile that wrote it, kept out of the legal sections', async ({ page }) => {
    await sampleStart(page)
    await page.goto('/reports?tab=pdpl')
    await fillOrg(page)
    await page.getByRole('button', { name: 'Save details' }).click()
    await expect(page.getByText('Organisation details saved').first()).toBeVisible()
    await page.getByRole('button', { name: 'Generate report' }).click()
    await page.getByRole('button', { name: 'Write AI commentary' }).click()
    const doc = page.getByRole('article', { name: /Information security and personal data assessment report/ })
    await expect(doc.getByText('AI-generated, needs human review')).toBeVisible()
    await expect(doc.getByText(/Model claude-sonnet-5-5 \(Claude Sonnet\)/)).toBeVisible()
  })
})

