// schemaFile is the schema of every module as a fresh install makes it, written by `make schema`.
const schemaFile = "../../docs/SCHEMA.sql"

// docs/SCHEMA.sql must be what the migrations make: `make schema` rewrites it (VEDETTE_WRITE_SCHEMA=1).
func TestSchemaFileIsCurrent(t *testing.T) {
	var b strings.Builder
	b.WriteString("-- The schema of every module as a fresh install makes it. Generated by `make schema` from the migrations: do\n")
	b.WriteString("-- not edit (a test fails when it is stale). Seed rows are in the migrations, not here.\n")
	b.WriteString("-- Schema epoch " + strconv.FormatInt(store.SchemaEpoch, 10) + ".\n")
	writeSchema(t, &b, "vedette.db", migrationSets(wiredModules()))
	writeSchema(t, &b, "logs.db", []store.MigrationSet{{Module: logs.ModuleID, FS: logs.VolumeMigrations}})
	got := b.String()
	if os.Getenv("VEDETTE_WRITE_SCHEMA") == "1" {
		if err := os.WriteFile(filepath.Clean(schemaFile), []byte(got), 0o644); err != nil { //nolint:gosec // a document in the repository
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(filepath.Clean(schemaFile))
	if err != nil {
		t.Fatal(err)
	}
	if string(want) != got {
		t.Fatal("docs/SCHEMA.sql is stale: run make schema and commit it")
	}
}

// writeSchema migrates a fresh database with sets, as start-up does, and writes each module's objects in the order SQLite
// keeps them (the tables an FTS5 table keeps for itself are left out).
func writeSchema(t *testing.T, b *strings.Builder, file string, sets []store.MigrationSet) {
	t.Helper()
	db := storetest.New(t)
	if err := store.CheckSchema(t.Context(), db, sets); err != nil {
		t.Fatal(err)
	}
	b.WriteString("\n-- ======== " + file + " ========\n")
	seen := map[string]bool{}
	section := func(title string) {
		var virtual []string
		var lines []string
		for _, o := range schemaObjects(t, db) {
			if seen[o.name] {
				continue
			}
			seen[o.name] = true
			if strings.HasPrefix(o.name, "core_migration_") || strings.HasPrefix(o.name, "sqlite_") || o.sql == "" || isShadow(o.name, virtual) {
				continue
			}
			if strings.HasPrefix(strings.ToUpper(o.sql), "CREATE VIRTUAL TABLE") {
				virtual = append(virtual, o.name)
			}
			lines = append(lines, o.sql+";\n")
		}
		b.WriteString("\n-- " + title + "\n\n" + strings.Join(lines, "\n"))
	}
	section("schema epoch (core/store)")
	for _, s := range sets {
		if err := store.Migrate(t.Context(), db, s.Module, s.FS); err != nil {
			t.Fatal(err)
		}
		section("module " + s.Module)
	}
}

type schemaObject struct{ name, sql string }

func schemaObjects(t *testing.T, db *store.DB) []schemaObject {
	t.Helper()
	rows, err := db.Reader().QueryContext(t.Context(), `SELECT name, coalesce(sql, '') FROM sqlite_master ORDER BY rowid`)
	if err != nil {
		t.Fatal(err)
	}
	var out []schemaObject
	for rows.Next() {
		var o schemaObject
		if err := rows.Scan(&o.name, &o.sql); err != nil {
			t.Fatal(err)
		}
		out = append(out, o)
	}
	if err := errors.Join(rows.Err(), rows.Close()); err != nil {
		t.Fatal(err)
	}
	return out
}

func isShadow(name string, virtual []string) bool {
	for _, v := range virtual {
		for _, s := range []string{"_data", "_idx", "_content", "_docsize", "_config"} {
			if name == v+s {
				return true
			}
		}
	}
	return false
}
