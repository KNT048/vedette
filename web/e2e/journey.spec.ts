import { expect, test, type Page } from '@playwright/test'
import { collectErrors } from './helpers'

// Real-user journey across modules on a clean install (no sample data). Desktop only; the module specs cover phones.
test.skip(({ isMobile }) => isMobile, 'desktop journey')
test.describe.configure({ timeout: 150_000 })

const shot = (page: Page, name: string) => page.screenshot({ path: `qa-shots/journey/${name}.png`, fullPage: true })

async function cleanInstall(page: Page, lan: string) {
  await page.goto('/login')
  await page.evaluate(() => localStorage.clear())
  await page.goto('/setup')
  await page.getByRole('checkbox', { name: 'I have read, understood and agree to the terms of use' }).click() // D-544: the terms of use come first
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByLabel('Setup code').fill('setup-code-demo') // D-75: the code the mock accepts
  await page.getByLabel('Organization name').fill('Northwind Trading')
  await page.getByLabel('Administrator name').fill('Alex Admin')
  await page.getByLabel('Sign-in email').fill('admin@northwind.example')
  await page.getByLabel('Password', { exact: true }).fill('a-very-long-password-123')
  await page.getByLabel('Repeat password').fill('a-very-long-password-123')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('textbox', { name: 'Range 1' }).fill(lan)
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('radio', { name: /Mid-size business/ }).click()
  await page.getByRole('button', { name: 'Finish setup' }).click()
  // The setup page has its own heading: wait until the app lands on Home, after the scope is saved
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('heading', { level: 1 }).first()).toBeVisible()
}

test('clean install, then manage subnets', async ({ page }) => {
  const errors = collectErrors(page)
  await cleanInstall(page, '192.168.18.0/25')
  await page.goto('/devices/setup')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await shot(page, '01-scope')
  const box = page.getByRole('textbox', { name: 'Add a network range' })
  // Bare address: refused, never turned into /24 (D-32)
  await box.fill('192.168.40.0')
  await box.press('Enter')
  await expect(page.getByText('"192.168.40.0" has no prefix length.', { exact: false })).toBeVisible()
  await expect(page.getByRole('list', { name: 'Ranges added' })).not.toContainText('192.168.40.0')
  // Enter adds a range
  await box.fill('192.168.30.0/24')
  await box.press('Enter')
  await expect(page.getByRole('list', { name: 'Ranges added' }).getByText('192.168.30.0/24')).toBeVisible()
  await page.getByRole('button', { name: 'Edit range 192.168.18.0/25' }).click()
  await expect(box).toHaveValue('192.168.18.0/25')
  await box.fill('192.168.18.0/24')
  await box.press('Enter')
  await page.getByRole('button', { name: 'Remove range 192.168.30.0/24' }).click()
  const ranges = page.getByRole('list', { name: 'Ranges added' })
  await expect(ranges.getByRole('listitem')).toHaveCount(1)
  await expect(ranges).toContainText('192.168.18.0/24')
  await expect(page.getByText('You added or changed ranges. Tick to confirm before saving.')).toBeVisible()
  await page.getByRole('checkbox', { name: /I confirm these network ranges/ }).check()
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByText('Scan scope saved.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('list', { name: 'Ranges added' })).toContainText('192.168.18.0/24')
  await expect(page.getByRole('list', { name: 'Ranges added' })).not.toContainText('192.168.18.0/25')
  await shot(page, '02-saved')
  // The box address everyone sees follows the first range
  await page.goto('/honeypot')
  await expect(page.locator('main')).toContainText('192.168.18.250')
  expect(errors).toEqual([])
})

test('add devices from the catalog', async ({ page }) => {
  const errors = collectErrors(page)
  await cleanInstall(page, '192.168.18.0/25')
  await page.goto('/devices')
  await shot(page, '10-devices-empty')
  async function add(query: string, pick: RegExp, fields: { version?: string; name?: string; ip?: string }) {
    await page.getByRole('button', { name: 'Add a device' }).first().click()
    const d = page.getByRole('dialog', { name: 'Add a device' })
    await d.getByRole('combobox', { name: 'Product' }).fill(query)
    await d.getByRole('option', { name: pick }).first().click()
    if (fields.version) await d.getByRole('textbox', { name: 'Version (optional)' }).fill(fields.version)
    if (fields.name) await d.getByRole('textbox', { name: 'Name (optional)' }).fill(fields.name)
    if (fields.ip) await d.getByRole('textbox', { name: 'IP address (optional)' }).fill(fields.ip)
    await d.getByRole('button', { name: 'Add', exact: true }).click()
    await expect(d).toBeHidden()
  }
  await add('fortigate 60f', /^FortiGate/, { version: '7.2.5', name: 'Office firewall', ip: '192.168.18.1' })
  await add('qnap', /QNAP/, { name: 'File server' })
  await expect(page.getByRole('heading', { level: 1 })).not.toHaveText('No devices yet')
  await shot(page, '11-devices-two')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('2 devices, all approved')
  await page.goto('/findings')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await shot(page, '12-findings')
  // Matched right away against the exploited list, as "suspected, product only" (S-INV-2)
  const row = page.getByRole('row', { name: /Office firewall/ })
  await expect(row).toContainText('CVE-2025-61624')
  await expect(row).toContainText('Product match only')
  await row.getByRole('link', { name: 'CVE-2025-61624' }).click()
  await expect(page).toHaveURL(/\/findings\/f-/)
  const findingUrl = page.url()
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await shot(page, '13-finding')
  await expect(page.getByRole('button', { name: 'Ask my AI' })).toBeDisabled()
  await expect(page.getByText('The AI assistant is off, or no AI profile is assigned to this job.').first()).toBeVisible()
  await page.goto('/settings/ai')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await shot(page, '14-ai-settings')
  await page.getByRole('button', { name: 'Add AI profile' }).first().click()
  const d = page.getByRole('dialog', { name: 'Add AI profile' })
  await d.getByRole('combobox', { name: 'Provider type' }).selectOption({ label: 'Custom' })
  await d.getByRole('textbox', { name: 'Profile name' }).fill('Company LLM gateway')
  await d.getByRole('textbox', { name: 'Server address' }).fill('https://llm.northwind.example/v1')
  await d.getByRole('textbox', { name: 'Model' }).fill('llama-4-70b')
  await d.getByRole('textbox', { name: 'API key' }).fill('test-key-abcd1234')
  await d.getByRole('radio', { name: 'Inside your network' }).check()
  const ack = d.getByRole('checkbox', { name: /I understand the data/ })
  if (await ack.count()) await ack.check()
  await d.getByRole('button', { name: 'Test connection' }).click()
  await page.waitForTimeout(800)
  await shot(page, '15-ai-profile-dialog')
  await d.getByRole('button', { name: 'Add profile' }).click()
  await expect(d).toBeHidden()
  // The first profile is assigned to every task at once, so the suggestion has nothing to change
  await page.getByRole('button', { name: 'Apply suggestion' }).click()
  await expect(page.getByText('Your saved routing already matches the suggestion. Nothing to save.')).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Primary profile for Explain findings' })).toHaveValue(/.+/)
  await shot(page, '16-ai-routing')
  await page.goto(findingUrl)
  const ask = page.getByRole('button', { name: 'Ask my AI' })
  await expect(ask).toBeEnabled()
  await ask.click()
  await expect(page.getByText(/Model llama-4-70b \(Company LLM gateway\)/)).toBeVisible()
  await expect(page.getByText('AI-generated, needs human review').first()).toBeVisible()
  await shot(page, '17-finding-ai')
  expect(errors).toEqual([])
})
