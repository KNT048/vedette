import { expect, test, type Page } from '@playwright/test'
import { collectErrors, expectAccessible, shot } from '../helpers'
import { DIACRITICS, finishClean, sampleStart } from './clean'

// QA module honeypot (S-HP-1, D-466): clean install -> add a Trap IP -> it listens on its own services -> test hit -> details;
// form errors under their own field; where each Trap IP lives; hits name their Trap IP (W1-13).
const SMB = 'SMB (file sharing)'
const call = (page: Page, path: string) => page.evaluate(async (p) => (await fetch(`/api/v1${p}`)).json(), path)
const vis = (page: Page, text: string | RegExp) => page.getByText(text).locator('visible=true').first()
const tab = (page: Page, name: RegExp) => page.getByRole('tab', { name }).click()

test('clean install: empty page with three steps, a Trap IP added with errors under each field, test hits are labelled', async ({ page, isMobile }) => {
  test.setTimeout(120_000)
  const errors = collectErrors(page)
  await finishClean(page)
  await page.goto('/honeypot')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/No Trap IP is on/)
  await expect(page.getByText('Get started with internal traps in three steps')).toBeVisible()
  await tab(page, /Services/)
  await expect(page.getByRole('button', { name: `Test trap ${SMB}` })).toBeDisabled()
  await tab(page, /Hits/)
  await expect(vis(page, /No Trap IP is on yet, so there is nothing to record/)).toBeVisible()
  await shot(page, 'honeypot', `clean-${isMobile ? 'mobile' : 'desktop'}`)
  await expectAccessible(page, 'honeypot clean')

  await tab(page, /Trap IPs/)
  await page.getByRole('button', { name: 'Add a Trap IP' }).click()
  const form = page.locator('form').filter({ has: page.getByLabel('Looks like') })
  const name = form.getByLabel('Name')
  const ip = form.getByLabel('Address')
  const add = form.getByRole('button', { name: 'Add Trap IP' })
  await add.click()
  await expect(page.locator('#tip-name-error')).toContainText('Enter a name, for example FILESRV-OLD.')
  await expect(page.locator('#tip-ip-error')).toContainText('Enter an address for the Trap IP.')
  await expect(name).toBeFocused()
  await name.fill('FILESRV-OLD')
  for (const [value, msg] of [['abc', /is not valid/], ['192.168.10.010', /no leading zeros/], ['10.0.0.5', /must be inside the box's network/], ['192.168.10.250', /own IP/], ['192.168.10.255', /not the network or broadcast address/]] as const) {
    await ip.fill(value); await add.click()
    await expect(page.locator('#tip-ip-error')).toContainText(msg)
    await expect(page.locator('#tip-name-error')).toHaveCount(0)
  }
  await ip.fill('192.168.10.240'); await name.fill('file.srv_old'); await add.click()
  await expect(page.locator('#tip-name-error')).toContainText('letters, digits and hyphens')
  await expect(name).toBeFocused()
  await name.fill('FILESRV-OLD'); await add.click()
  await expect(page.getByText('Trap IP FILESRV-OLD added')).toBeVisible()
  const details = page.getByLabel('Details of Trap IP FILESRV-OLD')
  await expect(details).toContainText('SMB (file sharing) 445, RDP (remote desktop) 3389')
  await expect(details).toContainText(/which a network scanner shows as Dell/)
  await expect(details).toContainText(/macvlan/)
  await page.reload()
  await expect(page.getByLabel('Details of Trap IP FILESRV-OLD')).toBeVisible()

  await tab(page, /Services/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/No trap was hit in the last 7 days/)
  await page.getByRole('button', { name: `Test trap ${SMB}` }).click()
  await expect(page.getByText('Recorded a test hit on the SMB (file sharing) trap').first()).toBeVisible()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/No trap was hit in the last 7 days/)
  await tab(page, /Hits/)
  const row = page.locator('tr:visible, li:visible').filter({ hasText: 'Vedette box (test)' }).first()
  await expect(row.getByText('Test', { exact: true })).toBeVisible()
  await expect(row.getByText('FILESRV-OLD')).toBeVisible()
  await row.getByRole('link').first().click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/Test hit on the SMB/)
  await expect(page.getByText(/Not an attacker/)).toBeVisible()
  await expect(page.getByText('What to do')).toHaveCount(0)
  await shot(page, 'honeypot', `hit-test-${isMobile ? 'mobile' : 'desktop'}`)
  await page.goto('/honeypot?tab=trap-ips')
  await page.getByRole('switch', { name: 'Trap IP FILESRV-OLD' }).click()
  await tab(page, /Services/)
  await expect(page.getByRole('button', { name: `Test trap ${SMB}` })).toBeDisabled()
  expect(errors).toEqual([])
})

test('sample: IP clash, name clash, where Trap IPs live, hit timeline, device page panel, missing hit', async ({ page, isMobile }) => {
  test.setTimeout(90_000)
  const errors = collectErrors(page)
  await sampleStart(page)
  await page.goto('/honeypot?tab=trap-ips')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/Traps were hit 5 times in 7 days/)
  await expect(page.getByLabel('Details of Trap IP FILESRV-OLD')).toContainText('vdhc0a80af0')
  await expect(page.getByText(/Last scan .* touched FILESRV-OLD, NAS-ARCHIVE, PRN-FLOOR2/)).toBeVisible()
  const devs = (await call(page, '/inventory/devices')).items as { ip: string; hostname: string | null; is_box?: boolean }[]
  const named = devs.find((d) => d.hostname && !d.is_box && d.ip.startsWith('192.168.10.'))!
  await page.getByRole('button', { name: 'Add a Trap IP' }).click()
  const form = page.locator('form').filter({ has: page.getByLabel('Looks like') })
  await form.getByLabel('Name').fill('FILESRV-02')
  await form.getByLabel('Address').fill(named.ip)
  await form.getByRole('button', { name: 'Add Trap IP' }).click()
  await expect(page.locator('#tip-ip-error')).toContainText('belongs to device')
  await form.getByLabel('Address').fill('192.168.10.245'); await form.getByLabel('Name').fill(named.hostname!)
  await form.getByRole('button', { name: 'Add Trap IP' }).click()
  await expect(page.locator('#tip-name-error')).toContainText('already used by a device')
  await form.getByLabel('Name').fill('FILESRV-02'); await form.getByRole('button', { name: 'Add Trap IP' }).click()
  await expect(page.getByText('Trap IP FILESRV-02 added')).toBeVisible()
  await shot(page, 'honeypot', `sample-${isMobile ? 'mobile' : 'desktop'}`)
  await expectAccessible(page, 'trap IPs')

  await tab(page, /Hits/)
  await expect(page.getByRole('table', { name: 'Trap hits' }).or(page.getByRole('list')).first()).toBeVisible()
  await page.getByRole('link', { name: /\d\d:\d\d/ }).first().click()
  await expect(page.getByRole('table', { name: 'Events around the trap hit' })).toBeVisible()
  await expect(page.getByText('What to do')).toBeVisible()
  await shot(page, 'honeypot', `hit-${isMobile ? 'mobile' : 'desktop'}`)
  await expectAccessible(page, 'hit detail')
  await page.locator('a[href^="/devices/"]').first().click()
  await expect(page.getByRole('heading', { name: 'Internal trap hits' })).toBeVisible()
  await expect(page.getByRole('link', { name: /SMB \(file sharing\) at/ })).toBeVisible()
  await expectAccessible(page, 'device page with trap panel')
  await page.goto('/honeypot/hits/no-such-hit')
  await expect(page.getByRole('alert')).toContainText('No such trap hit')
  expect(errors).toEqual([])
})

test('English only and dark mode: no Vietnamese, error under the right field', async ({ page }) => {
  const errors = collectErrors(page)
  await sampleStart(page)
  await page.emulateMedia({ colorScheme: 'dark' })
  for (const path of ['/honeypot?tab=trap-ips', '/honeypot?tab=hits', '/honeypot/hits/hit-seed-1', '/honeypot/hits/hit-seed-2']) {
    await page.goto(path)
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    if (path.endsWith('trap-ips')) {
      await page.getByRole('button', { name: 'Add a Trap IP' }).click()
      const form = page.locator('form').filter({ has: page.getByLabel('Looks like') })
      await form.getByLabel('Name').fill('FILESRV-02')
      await form.getByLabel('Address').fill('192.168.10.250')
      await form.getByRole('button', { name: 'Add Trap IP' }).click()
      await expect(page.locator('#tip-ip-error')).toContainText(/Vedette box's own IP/)
    }
    const text = (await page.locator('main').innerText()).replace(/Sample data/g, '')
    expect(text.match(DIACRITICS), `${path} contains Vietnamese: ${text.match(/.{20}[ăâđêôơư].{20}/i)?.[0]}`).toBeNull()
    await shot(page, 'honeypot', `dark-${path.replace(/\W/g, '_')}`)
    await expectAccessible(page, `${path} dark`)
  }
  expect(errors).toEqual([])
})
